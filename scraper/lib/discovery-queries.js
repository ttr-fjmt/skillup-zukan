/**
 * ジャンルの追加・削除時に GENRE とクエリ表の間にズレが出ると、そのジャンルだけ
 * 静かに発見されなくなる（既存サイトで実際に2つの一覧がズレる問題があった）。
 * 読み込み時点で必ず落とす。
 */
for (const genre of GENRE) {
  const queries = DISCOVERY_QUERIES[genre];
  if (!Array.isArray(queries) || queries.length < QUERY_WINDOW) {
    throw new Error(
      `discovery-queries: GENRE "${genre}" のクエリが${QUERY_WINDOW}件未満です（現在: ${queries ? queries.length : 0}件）`
    );
  }
  const unique = new Set(queries);
  if (unique.size !== queries.length) {
    throw new Error(`discovery-queries: GENRE "${genre}" に重複したクエリがあります`);
  }
}
for (const genre of Object.keys(DISCOVERY_QUERIES)) {
  if (!GENRE.includes(genre)) {
    throw new Error(`discovery-queries: 未知のジャンル "${genre}" が定義されています（lib/schema.js の GENRE に存在しません）`);
  }
}

/**
 * 日付に応じて、使う切り口の「窓」をずらす。
 *
 * 1回の呼び出しで実際に検索できる回数には上限があるため、20〜30本すべてを毎回
 * 並べても上から数本しか使われない。日ごとに開始位置をずらすことで、日をまたいで
 * すべての切り口が順番に使われる（1周するのに数日かかる）。
 * 起点はJSTの通算日。日次cronがJST 5:00に動くため、日付境界をJSTに合わせる。
 */
function rotateQueries(queries, date = new Date(), size = QUERY_WINDOW) {
  if (queries.length <= size) return [...queries];
  const jst = new Date(date.getTime() + 9 * 60 * 60 * 1000);
  const dayOfYear = Math.floor((jst - Date.UTC(jst.getUTCFullYear(), 0, 0)) / 86400000);
  const start = (dayOfYear * size) % queries.length;
  const out = [];
  for (let i = 0; i < size; i += 1) out.push(queries[(start + i) % queries.length]);
  return out;
}

/** 発見プロンプトに埋め込むための、ジャンル1件分の「日本語ラベル＋検索の切り口」。 */
function queriesForGenre(genre, date = new Date()) {
  return { label: GENRE_LABELS[genre], queries: rotateQueries(DISCOVERY_QUERIES[genre], date) };
}

